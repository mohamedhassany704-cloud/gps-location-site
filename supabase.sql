create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  latitude double precision not null,
  longitude double precision not null,
  accuracy double precision,
  device text,
  created_at timestamptz not null default now()
);

alter table public.locations enable row level security;

-- السماح للزوار غير المسجلين بإضافة سجل فقط.
-- لا تمنحهم صلاحية قراءة السجلات أو تعديلها أو حذفها.
drop policy if exists "Allow anonymous location insert" on public.locations;
create policy "Allow anonymous location insert"
on public.locations
for insert
to anon
with check (
  latitude between -90 and 90
  and longitude between -180 and 180
  and (accuracy is null or accuracy >= 0)
);

grant insert on table public.locations to anon;
grant usage, select on sequence public.locations_id_seq to anon;
